/** The room's pools: its levels' cards, in catalog order. */
export function retoPools(levels: RetoLevel[]): { verdades: string[]; retos: string[] } {
  const chosen = RETO_LEVELS.filter((l) => levels.includes(l.id));
  return { verdades: chosen.flatMap((l) => l.verdades), retos: chosen.flatMap((l) => l.retos) };
}
